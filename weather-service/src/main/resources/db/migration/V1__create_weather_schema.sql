-- weather-service schema (portable: runs on H2 and PostgreSQL)
CREATE TABLE locations (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(120)     NOT NULL,
    country    VARCHAR(80),
    latitude   DOUBLE PRECISION NOT NULL,
    longitude  DOUBLE PRECISION NOT NULL,
    version    BIGINT           NOT NULL DEFAULT 0,
    created_at TIMESTAMP,
    updated_at TIMESTAMP,
    CONSTRAINT uq_location_coords UNIQUE (latitude, longitude)
);

CREATE TABLE weather_snapshots (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    location_id          BIGINT           NOT NULL REFERENCES locations (id),
    observed_at          TIMESTAMP        NOT NULL,
    temperature          DOUBLE PRECISION NOT NULL,
    apparent_temperature DOUBLE PRECISION NOT NULL,
    humidity             INTEGER          NOT NULL,
    wind_speed           DOUBLE PRECISION NOT NULL,
    precipitation        DOUBLE PRECISION NOT NULL,
    weather_code         INTEGER          NOT NULL,
    is_day               BOOLEAN          NOT NULL DEFAULT TRUE,
    created_at           TIMESTAMP,
    updated_at           TIMESTAMP
);
CREATE INDEX idx_snapshot_location_time ON weather_snapshots (location_id, observed_at);

CREATE TABLE daily_weather (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    location_id       BIGINT           NOT NULL REFERENCES locations (id),
    weather_date      DATE             NOT NULL,
    temp_max          DOUBLE PRECISION NOT NULL,
    temp_min          DOUBLE PRECISION NOT NULL,
    precipitation_sum DOUBLE PRECISION NOT NULL,
    wind_speed_max    DOUBLE PRECISION NOT NULL,
    weather_code      INTEGER          NOT NULL,
    CONSTRAINT uq_daily_location_date UNIQUE (location_id, weather_date)
);

CREATE TABLE fetch_audit_log (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    endpoint    VARCHAR(40)      NOT NULL,
    latitude    DOUBLE PRECISION NOT NULL,
    longitude   DOUBLE PRECISION NOT NULL,
    success     BOOLEAN          NOT NULL,
    duration_ms BIGINT           NOT NULL,
    message     VARCHAR(255),
    created_at  TIMESTAMP        NOT NULL
);
