-- alert-service schema (portable: runs on H2 and PostgreSQL)
CREATE TABLE alert_rules (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username          VARCHAR(40)      NOT NULL,
    location_name     VARCHAR(120)     NOT NULL,
    latitude          DOUBLE PRECISION NOT NULL,
    longitude         DOUBLE PRECISION NOT NULL,
    metric            VARCHAR(30)      NOT NULL,
    threshold         DOUBLE PRECISION NOT NULL,
    active            BOOLEAN          NOT NULL DEFAULT TRUE,
    last_triggered_at TIMESTAMP,
    version           BIGINT           NOT NULL DEFAULT 0,
    created_at        TIMESTAMP,
    updated_at        TIMESTAMP
);
CREATE INDEX idx_rule_user ON alert_rules (username);
CREATE INDEX idx_rule_active ON alert_rules (active);

CREATE TABLE weather_alerts (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rule_id        BIGINT REFERENCES alert_rules (id) ON DELETE SET NULL,
    username       VARCHAR(40)      NOT NULL,
    location_name  VARCHAR(120)     NOT NULL,
    latitude       DOUBLE PRECISION NOT NULL,
    longitude      DOUBLE PRECISION NOT NULL,
    type           VARCHAR(30)      NOT NULL,
    severity       VARCHAR(10)      NOT NULL,
    message        VARCHAR(255)     NOT NULL,
    observed_value DOUBLE PRECISION NOT NULL,
    threshold      DOUBLE PRECISION NOT NULL,
    acknowledged   BOOLEAN          NOT NULL DEFAULT FALSE,
    created_at     TIMESTAMP
);
CREATE INDEX idx_alert_user_time ON weather_alerts (username, created_at);
